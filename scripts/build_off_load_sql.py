"""Build the Snowflake load script for the Open Food Facts India extract.

Reads the header of off_india_raw.tsv (211 columns), cleans the column names
for Snowflake, writes load/01_load_open_food_facts.sql, and gzips the TSV to
data/raw/ for a faster upload.

Usage (from the project root):
    python scripts/build_off_load_sql.py
"""
import gzip
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_TSV = ROOT / "off_india_raw.tsv"
GZ_OUT = ROOT / "data" / "raw" / "off_india_raw.tsv.gz"
SQL_OUT = ROOT / "load" / "01_load_open_food_facts.sql"

# Snowflake reserved words that could clash with a column name
RESERVED = {
    "all", "alter", "and", "any", "as", "between", "by", "case", "cast", "check",
    "column", "connect", "create", "current", "delete", "distinct", "drop", "else",
    "exists", "following", "for", "from", "full", "grant", "group", "having", "ilike",
    "in", "increment", "inner", "insert", "intersect", "into", "is", "join", "lateral",
    "left", "like", "minus", "natural", "not", "null", "of", "on", "or", "order",
    "qualify", "regexp", "revoke", "right", "rlike", "row", "rows", "sample", "select",
    "set", "some", "start", "table", "tablesample", "then", "to", "trigger", "true",
    "try_cast", "union", "unique", "update", "using", "values", "when", "whenever",
    "where", "with",
}


def clean(name: str) -> str:
    """energy-kcal_100g -> energy_kcal_100g; prefix a leading digit; avoid reserved words."""
    col = re.sub(r"[^a-z0-9_]", "_", name.strip().lower())
    if col[0].isdigit():
        col = "c_" + col
    if col in RESERVED:
        col = col + "_"
    return col


def main() -> None:
    with SRC_TSV.open(encoding="utf-8") as f:
        header = f.readline().rstrip("\n").split("\t")

    cols = [clean(h) for h in header]
    if len(set(cols)) != len(cols):
        raise SystemExit("Duplicate column names after cleaning: fix clean()")
    renamed = [(h, c) for h, c in zip(header, cols) if h != c]

    ddl_cols = ",\n".join(f"    {c:<45} VARCHAR" for c in cols)
    insert_cols = ",\n".join(f"    {c}" for c in cols)
    select_cols = ",\n".join(f"    ${i}" for i in range(1, len(cols) + 1))

    sql = f"""/* =====================================================================
   GoDesi Analytics — Phase 2a: load the Open Food Facts India extract
   ---------------------------------------------------------------------
   GENERATED by scripts/build_off_load_sql.py — edit the script, not this file.

   Source file : data/raw/off_india_raw.tsv.gz  ({len(cols)} columns, tab-separated)
   Target table: GODESI_RAW.OPEN_FOOD_FACTS.PRODUCTS (all VARCHAR, as raw data should be)
   Role        : LOADER

   Run sections 1-2, upload the file (see load/README.md), then run 3-5.
   {len(renamed)} column names were changed for Snowflake (hyphens -> underscores),
   e.g. {renamed[0][0]} -> {renamed[0][1]}.
   ===================================================================== */

USE ROLE LOADER;
USE WAREHOUSE GODESI_WH;
USE SCHEMA GODESI_RAW.OPEN_FOOD_FACTS;


/* ---------------------------------------------------------------------
   1. File format: how Snowflake should read the file
   --------------------------------------------------------------------- */
CREATE OR REPLACE FILE FORMAT GODESI_RAW.OPEN_FOOD_FACTS.OFF_TSV_FORMAT
  TYPE                         = CSV
  FIELD_DELIMITER              = '\\t'
  RECORD_DELIMITER             = '\\n'
  SKIP_HEADER                  = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = NONE    -- some product names contain "quotes"
  ESCAPE_UNENCLOSED_FIELD      = NONE    -- a few fields contain backslashes
  EMPTY_FIELD_AS_NULL          = TRUE
  TRIM_SPACE                   = FALSE   -- raw layer keeps data untouched
  ENCODING                     = 'UTF8'
  REPLACE_INVALID_CHARACTERS   = TRUE
  COMPRESSION                  = AUTO    -- detects .gz
  COMMENT                      = 'Open Food Facts tab-separated export';


/* ---------------------------------------------------------------------
   2. Internal stage: a landing folder inside Snowflake for the file
   --------------------------------------------------------------------- */
CREATE STAGE IF NOT EXISTS GODESI_RAW.OPEN_FOOD_FACTS.OFF_STAGE
  FILE_FORMAT = GODESI_RAW.OPEN_FOOD_FACTS.OFF_TSV_FORMAT
  DIRECTORY   = (ENABLE = TRUE)                 -- lets Snowsight list the files
  ENCRYPTION  = (TYPE = 'SNOWFLAKE_SSE')        -- needed for Snowsight uploads
  COMMENT     = 'Landing area for Open Food Facts files';

-- >>> Now upload data/raw/off_india_raw.tsv.gz to OFF_STAGE (load/README.md, step 3) <<<


/* ---------------------------------------------------------------------
   3. Check the file arrived
   --------------------------------------------------------------------- */
LIST @GODESI_RAW.OPEN_FOOD_FACTS.OFF_STAGE;                                -- expect off_india_raw.tsv.gz

-- Peek at the first rows straight from the stage, before loading
SELECT $1 AS code, $11 AS product_name, $19 AS brands, $5 AS created_datetime
FROM @GODESI_RAW.OPEN_FOOD_FACTS.OFF_STAGE (FILE_FORMAT => 'GODESI_RAW.OPEN_FOOD_FACTS.OFF_TSV_FORMAT')
LIMIT 10;


/* ---------------------------------------------------------------------
   4. Raw table + load
   --------------------------------------------------------------------- */
CREATE OR REPLACE TABLE GODESI_RAW.OPEN_FOOD_FACTS.PRODUCTS (
{ddl_cols},
    _source_file                                  VARCHAR,
    _source_row_number                            NUMBER,
    _loaded_at                                    TIMESTAMP_LTZ
)
COMMENT = 'Open Food Facts products sold in India (raw, untyped). Licence: ODbL.';

COPY INTO GODESI_RAW.OPEN_FOOD_FACTS.PRODUCTS (
{insert_cols},
    _source_file,
    _source_row_number,
    _loaded_at
)
FROM (
  SELECT
{select_cols},
    METADATA$FILENAME,
    METADATA$FILE_ROW_NUMBER,
    CURRENT_TIMESTAMP()
  FROM @GODESI_RAW.OPEN_FOOD_FACTS.OFF_STAGE
)
FILE_FORMAT = (FORMAT_NAME = 'GODESI_RAW.OPEN_FOOD_FACTS.OFF_TSV_FORMAT')
ON_ERROR    = 'ABORT_STATEMENT';               -- all-or-nothing: any bad row stops the load

-- Result panel: status LOADED, rows_parsed = rows_loaded = 26293, errors_seen = 0


/* ---------------------------------------------------------------------
   5. Verify
   --------------------------------------------------------------------- */
SELECT COUNT(*) AS row_count, COUNT(DISTINCT code) AS unique_codes
FROM GODESI_RAW.OPEN_FOOD_FACTS.PRODUCTS;                                -- expect 26293 and 26293

SELECT code, product_name, brands, quantity, main_category_en,
       energy_kcal_100g, sugars_100g, nutriscore_grade
FROM GODESI_RAW.OPEN_FOOD_FACTS.PRODUCTS
WHERE LOWER(brands) LIKE '%go desi%'
ORDER BY product_name;                          -- the GoDesi products

SELECT *
FROM TABLE(GODESI_RAW.INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME => 'GODESI_RAW.OPEN_FOOD_FACTS.PRODUCTS',
  START_TIME => DATEADD(HOUR, -1, CURRENT_TIMESTAMP())
));                                             -- load history: status Loaded, 0 errors

-- Can dbt's role read it? (should return the same count)
USE ROLE TRANSFORMER;
SELECT COUNT(*) FROM GODESI_RAW.OPEN_FOOD_FACTS.PRODUCTS;
USE ROLE LOADER;
"""
    SQL_OUT.parent.mkdir(parents=True, exist_ok=True)
    SQL_OUT.write_text(sql, encoding="utf-8")

    GZ_OUT.parent.mkdir(parents=True, exist_ok=True)
    with SRC_TSV.open("rb") as src, gzip.open(GZ_OUT, "wb", compresslevel=9) as dst:
        shutil.copyfileobj(src, dst)

    print(f"columns: {len(cols)}  renamed: {len(renamed)}")
    print(f"wrote {SQL_OUT.relative_to(ROOT)}")
    print(f"wrote {GZ_OUT.relative_to(ROOT)}  ({GZ_OUT.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
